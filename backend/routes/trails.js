const router = require('express').Router();
const { body, param } = require('express-validator');
const auth = require('../middleware/auth');
const validate = require('../middleware/validate');
const controller = require('../controllers/trailController');
router.use(auth);
router.post('/', [body('trailName').trim().isLength({ min: 2 }), body('description').optional().trim().isLength({ max: 500 }), body('siteIds').isArray({ min: 1 }).custom(ids => ids.every(id => typeof id === 'string' && id.trim()))], validate, controller.create);
router.get('/', controller.list);
router.get('/:id', [param('id').isMongoId()], validate, controller.get);
router.put('/:id', [param('id').isMongoId(), body('trailName').optional().trim().isLength({ min: 2 }), body('description').optional().trim().isLength({ max: 500 }), body('siteIds').optional().isArray({ min: 1 }).custom(ids => ids.every(siteId => typeof siteId === 'string' && siteId.trim()))], validate, controller.update);
router.delete('/:id', [param('id').isMongoId()], validate, controller.remove);
module.exports = router;
